-- =====================================================================
-- 本体动作执行记录补「编辑目标物理表」字段（人为编辑登记 / 冲突仲裁）
-- =====================================================================
-- 背景：
--   数据接收工程（datamaster-ingestion）周期性把数据集成结果写入数仓副本，
--   ONT_ACTION_EXECUTION 中的执行记录同时承载「人工编辑登记」的职责。
--   为让接收工程能按「目标物理表 + 主键」定位人为编辑做字段级仲裁/第三值告警，
--   需要给执行记录标记本次写动作作用的物理表。
--   该字段为被动元数据（执行写动作时打标），不改动动作执行语义。
-- =====================================================================

ALTER TABLE ONT_ACTION_EXECUTION ADD COLUMN target_table varchar(255);

-- 兼容性提示：老版本无该字段；执行记录在字段补齐前默认为 NULL。
